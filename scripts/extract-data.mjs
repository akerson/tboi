// Builds js/data.js from the reference files in reference/ (see README "Rebuilding the data").
//
//   reference/rep/item_data.h, main.cpp       frto027/IsaacDecraftingHuijiGadget @ af9fb78 (Repentance v1.7.9b)
//   reference/repplus/item_data.h, main.cpp   frto027/IsaacDecraftingHuijiGadget @ abd3370 (Repentance+ v1.9.7.15)
//   reference/items.xml                       English item names + in-game pickup quotes
//   reference/sprite_css.txt                  #collectibles_NNN sprite offsets into assets/collectibles.png
//
// Usage: node scripts/extract-data.mjs

import { readFileSync, writeFileSync } from 'node:fs';

const read = path => readFileSync(new URL('../reference/' + path, import.meta.url), 'utf8');

function block(text, name) {
  const match = text.match(new RegExp(name + '\\[\\]\\s*=\\s*\\{([\\s\\S]*?)\\n\\};'));
  if (!match) throw new Error('missing block ' + name);
  return match[1];
}
const rows = text => [...text.matchAll(/\{([^{}]*)\}/g)].map(m => m[1].split(',').map(s => s.trim()));

const TAGS = ['lazarusshared', 'nodaily', 'offensive', 'nolostbr', 'nokeeper', 'nogreed', 'nochallenge'];

function extractVersion(dir) {
  const header = read(dir + '/item_data.h');
  const cpp = read(dir + '/main.cpp');

  const entries = rows(block(header, 'item_pool_datas')).map(([id, weight]) => [Number(id), Number(weight)]);
  // Pool order matters: the game sums float weights in this order.
  const pools = rows(block(header, 'item_pool_metadata')).map(([start, length]) =>
    Number(start) < 0 ? [] : entries.slice(Number(start), Number(start) + Number(length)));

  // Per item: [achievement id, crafting quality, tag names]. Quality -1 means "no such item".
  const items = rows(block(header, 'item_config_datas')).map(([aid, quality, , tags]) => [
    Number(aid),
    Number(quality),
    [...(tags ?? '').matchAll(/TAG_(\w+)/g)].map(m => m[1].toLowerCase()).filter(t => TAGS.includes(t)),
  ]);

  // Fixed recipes are stored as the 8 sorted pickup ids packed into a uint64, lowest byte first.
  const fixed = rows(block(cpp, '\\}predefined_recipes')).map(([packed, output]) => {
    let value = BigInt(packed);
    const recipe = [];
    for (let i = 0; i < 8; i++) { recipe.push(Number(value & 0xFFn)); value >>= 8n; }
    return [recipe.join(','), Number(output)];
  });

  return { pools, items, fixed: Object.fromEntries(fixed) };
}

function extractNames() {
  const xml = read('items.xml');
  const names = {};
  for (const [tag] of xml.matchAll(/<(?:passive|active|familiar)\b[^>]*>/g)) {
    const attr = key => tag.match(new RegExp('\\s' + key + '="([^"]*)"'))?.[1];
    const decode = s => s?.replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>');
    names[attr('id')] = [decode(attr('name')), decode(attr('description')) ?? ''];
  }
  // Items missing from the 2021 items.xml snapshot (added in later patches, or hidden).
  Object.assign(names, {
    59: ['The Book of Belial', ''],
    730: ['Glass Eye', ''],
    731: ['Stye', ''],
    732: ["Mom's Ring", ''],
  });
  return names;
}

function extractSprites() {
  const css = read('sprite_css.txt');
  const sprites = {};
  for (const [, id, x, y] of css.matchAll(/#collectibles_(\d+)\{background-position:-(\d+)px -(\d+)px;\}/g)) {
    sprites[Number(id)] = [Number(x) / 32, Number(y) / 32];
  }
  return sprites;
}

const data = {
  versions: {
    rep: { label: 'Repentance (v1.7.9b)', ...extractVersion('rep') },
    repplus: { label: 'Repentance+ (v1.9.7.15)', ...extractVersion('repplus') },
  },
  names: extractNames(),
  sprites: extractSprites(),
};

for (const [key, v] of Object.entries(data.versions)) {
  const real = v.items.filter(([, q]) => q >= 0).length;
  console.log(`${key}: ${v.pools.length} pools, ${v.items.length} item slots (${real} items), ${Object.keys(v.fixed).length} fixed recipes`);
}
console.log(`names: ${Object.keys(data.names).length}, sprites: ${Object.keys(data.sprites).length}`);

const missingNames = data.versions.repplus.items.map(([, q], id) => q >= 0 && !data.names[id] ? id : null).filter(id => id !== null);
if (missingNames.length) console.warn('items without names:', missingNames.join(','));

writeFileSync(new URL('../js/data.js', import.meta.url),
  '// Generated by scripts/extract-data.mjs. Do not edit by hand.\n' +
  'export default ' + JSON.stringify(data) + ';\n');
